import {
  ContractSpecAST,
  UnionCaseDoc,
  FunctionParamDoc,
  TypeDescriptor,
} from "../ast.js";

/**
 * Maps a Soroban AST TypeDescriptor to a TypeScript type string.
 */
export function formatTypeScriptType(type: TypeDescriptor): string {
  switch (type.kind) {
    case "primitive":
      switch (type.name) {
        case "bool":
          return "boolean";
        case "void":
          return "void";
        case "u32":
        case "i32":
          return "number";
        case "u64":
        case "i64":
        case "u128":
        case "i128":
        case "u256":
        case "i256":
        case "timepoint":
        case "duration":
          return "bigint";
        case "string":
        case "symbol":
        case "address":
        case "muxedAddress":
          return "string";
        case "bytes":
          return "Uint8Array";
        case "val":
          return "unknown";
        case "error":
          return "Error";
      }
      break;

    case "bytesN":
      return "Uint8Array";

    case "option":
      return `${formatTypeScriptType(type.valueType)} | undefined`;

    case "result":
      return `{ ok: ${formatTypeScriptType(type.okType)} } | { err: ${formatTypeScriptType(type.errorType)} }`;

    case "vec":
      return `Array<${formatTypeScriptType(type.elementType)}>`;

    case "map":
      return `Map<${formatTypeScriptType(type.keyType)}, ${formatTypeScriptType(type.valueType)}>`;

    case "tuple":
      return `[${type.elementTypes.map(formatTypeScriptType).join(", ")}]`;

    case "udt":
      return type.name;

    case "unsupported":
      return "unknown";
  }

  return "unknown";
}

/**
 * Generates TypeScript type definitions and a typed client interface from a normalized AST.
 */
export function generateTypeScript(ast: ContractSpecAST, contractName = "ContractClient"): string {
  const lines: string[] = [
    "/* Autogenerated by SoroDoc — Do not edit manually */",
    "",
  ];

  // Enums
  for (const e of ast.enums) {
    if (e.doc) {
      lines.push(`/** ${e.doc.replace(/\n/g, " ")} */`);
    }
    lines.push(`export enum ${e.name} {`);
    for (const c of e.cases) {
      if (c.doc) {
        lines.push(`  /** ${c.doc.replace(/\n/g, " ")} */`);
      }
      lines.push(`  ${c.name} = ${c.value},`);
    }
    lines.push("}", "");
  }

  // Error Enums
  for (const ee of ast.errorEnums) {
    if (ee.doc) {
      lines.push(`/** ${ee.doc.replace(/\n/g, " ")} */`);
    }
    lines.push(`export enum ${ee.name} {`);
    for (const c of ee.cases) {
      if (c.doc) {
        lines.push(`  /** ${c.doc.replace(/\n/g, " ")} */`);
      }
      lines.push(`  ${c.name} = ${c.value},`);
    }
    lines.push("}", "");
  }

  // Structs
  for (const s of ast.structs) {
    if (s.doc) {
      lines.push(`/** ${s.doc.replace(/\n/g, " ")} */`);
    }
    lines.push(`export interface ${s.name} {`);
    for (const f of s.fields) {
      if (f.doc) {
        lines.push(`  /** ${f.doc.replace(/\n/g, " ")} */`);
      }
      lines.push(`  ${f.name}: ${formatTypeScriptType(f.type)};`);
    }
    lines.push("}", "");
  }

  // Unions
  for (const u of ast.unions) {
    if (u.doc) {
      lines.push(`/** ${u.doc.replace(/\n/g, " ")} */`);
    }
    if (u.cases.length === 0) {
      lines.push(`export type ${u.name} = never;`, "");
    } else {
      const caseTypes = u.cases.map((c: UnionCaseDoc) => {
        if (c.kind === "void") {
          return `{ tag: "${c.name}" }`;
        }
        const values = c.types.map(formatTypeScriptType).join(", ");
        return `{ tag: "${c.name}"; values: [${values}] }`;
      });
      lines.push(`export type ${u.name} =`);
      for (const ct of caseTypes) {
        lines.push(`  | ${ct}`);
      }
      lines.push(";", "");
    }
  }

  // Contract Client Interface
  lines.push(`export interface ${contractName} {`);
  for (const fn of ast.functions) {
    if (fn.doc) {
      lines.push(`  /** ${fn.doc.replace(/\n/g, " ")} */`);
    }
    const params = fn.inputs.map((i: FunctionParamDoc) => `${i.name}: ${formatTypeScriptType(i.type)}`).join(", ");
    let returnType = "void";
    if (fn.outputs.length === 1) {
      returnType = formatTypeScriptType(fn.outputs[0]!);
    } else if (fn.outputs.length > 1) {
      returnType = `[${fn.outputs.map(formatTypeScriptType).join(", ")}]`;
    }
    lines.push(`  ${fn.name}(${params}): Promise<${returnType}>;`);
  }
  lines.push("}", "");

  return lines.join("\n").trim() + "\n";
}
